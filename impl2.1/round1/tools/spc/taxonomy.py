# ── meta 构造辅助 ──────────────────────────────────────────────────────────────
def make_meta(
    topic: str,
    subtopic: str,
    role: str,
    industry: str,
    process: str,
    style: str,
    skill_doc: bool,
    difficulty: str = "intermediate",
    sample_type: str = "textbook",
) -> dict:
    """构造标准 meta 字段。"""
    assert topic in TOPICS or topic in ("multi_rule", "fundamentals", "ucl_lsl", "zone", "cpk"), f"未知 topic: {topic}"
    assert subtopic in SUBTOPICS, f"未知 subtopic: {subtopic}"
    assert role in ROLES, f"未知 role: {role}"
    assert industry in INDUSTRY_PROCESS, f"未知 industry: {industry}"
    assert style in STYLES, f"未知 style: {style}"
    assert difficulty in ("basic", "intermediate", "advanced")
    assert sample_type in ("textbook", "spc_analysis", "golden")
    return {
        "type": sample_type,
        "topic": topic,
        "subtopic": subtopic,
        "role": role,
        "industry": industry,
        "process": process,
        "style": style,
        "skill_doc": skill_doc,
        "difficulty": difficulty,
    }
